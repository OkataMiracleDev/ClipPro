"""Third-party licence inventory and check (PLAN P14.6).

Writes app/src-tauri/licenses/THIRD-PARTY-RUST.md (every crate the desktop app links) and
THIRD-PARTY-JS.md (the UI's production npm packages), and exits non-zero when a dependency's
licence isn't on the allow list. Run from the repo root after `source scripts/env.sh`:

    python scripts/licenses.py
"""

import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "src-tauri", "licenses")

# Permissive licences, plus weak copyleft that is fine for an unmodified, dynamically used
# dependency (MPL-2.0 is file-level). GPL/AGPL/LGPL crates would need review.
ALLOWED = {
    "MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016",
    "CC0-1.0", "0BSD", "BSL-1.0", "MPL-2.0", "Unlicense", "Apache-2.0 WITH LLVM-exception", "CDLA-Permissive-2.0",
    "MIT-0", "BlueOak-1.0.0", "Python-2.0", "CC-BY-4.0", "WTFPL", "OFL-1.1", "NCSA", "bzip2-1.0.6",
}


def acceptable(expr: str) -> bool:
    """An SPDX expression is acceptable when one OR-branch is all allowed."""
    if not expr:
        return False
    expr = expr.replace("/", " OR ").replace("(", " ").replace(")", " ")
    for branch in re.split(r"\s+OR\s+", expr):
        parts = [p.strip() for p in re.split(r"\s+AND\s+", branch) if p.strip()]
        if parts and all(p in ALLOWED for p in parts):
            return True
    return False


def rust() -> list[str]:
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"], cwd=ROOT))
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    app = next(p["id"] for p in meta["packages"] if p["name"] == "clippro-app")
    # Normal (linked) dependencies reachable from the app; build and dev dependencies aren't shipped.
    seen, stack = set(), [app]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    members = set(meta["workspace_members"])
    rows, bad = [], []
    for i in sorted(seen - members, key=lambda x: (pkgs[x]["name"], pkgs[x]["version"])):
        p = pkgs[i]
        lic = p.get("license") or ("see " + os.path.basename(p["license_file"]) if p.get("license_file") else "")
        if not acceptable(p.get("license") or ""):
            bad.append(f"{p['name']} {p['version']}: {lic or 'no licence field'}")
        rows.append(f"| {p['name']} | {p['version']} | {lic} | {p.get('repository') or ''} |")
    with open(os.path.join(OUT, "THIRD-PARTY-RUST.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Rust crates in ClipPro\n\nGenerated by `scripts/licenses.py`.\n\n| Crate | Version | Licence | Source |\n|---|---|---|---|\n")
        f.write("\n".join(rows) + "\n")
    print(f"rust: {len(rows)} crates")
    return bad


def js() -> list[str]:
    lock = json.load(open(os.path.join(ROOT, "app", "ui", "package-lock.json"), encoding="utf-8"))
    rows, bad = [], []
    for path, p in sorted(lock.get("packages", {}).items()):
        if not path or p.get("dev") or p.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        pj = os.path.join(ROOT, "app", "ui", path, "package.json")
        lic = p.get("license")
        if not lic and os.path.exists(pj):
            lic = json.load(open(pj, encoding="utf-8")).get("license", "")
        lic = lic if isinstance(lic, str) else str(lic)
        if not acceptable(lic):
            bad.append(f"{name} {p.get('version')}: {lic or 'no licence field'}")
        rows.append(f"| {name} | {p.get('version', '')} | {lic} |")
    with open(os.path.join(OUT, "THIRD-PARTY-JS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# JavaScript packages in the ClipPro UI\n\nGenerated by `scripts/licenses.py`.\n\n| Package | Version | Licence |\n|---|---|---|\n")
        f.write("\n".join(rows) + "\n")
    print(f"js: {len(rows)} packages")
    return bad


def main() -> int:
    os.makedirs(OUT, exist_ok=True)
    bad = rust() + js()
    for b in bad:
        print("NOT ALLOWED:", b)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
